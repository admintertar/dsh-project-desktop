import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync} from 'node:fs';
import {join} from 'node:path';
import {repository} from '../src/desktop-adapter/paths.mjs';
import {findProjectFile, createProjectInDirectory, RecentProjects} from '../src/app/project-files.mjs';
mkdirSync(join(repository, '.runtime'), {recursive: true});
const root = mkdtempSync(join(repository, '.runtime/project-files-'));
const directory = join(root, 'My Project'); mkdirSync(directory);
assert.equal(findProjectFile(directory), undefined);
const manifest = await createProjectInDirectory(directory);
assert.equal(manifest, join(directory, 'My Project.agent-project'));
const original = readFileSync(manifest, 'utf8');
assert.equal(await createProjectInDirectory(directory), manifest);
assert.equal(readFileSync(manifest, 'utf8'), original);
writeFileSync(join(directory, 'Second.agent-project'), original);
await assert.rejects(createProjectInDirectory(directory), /多个项目/);
assert.equal(readFileSync(manifest, 'utf8'), original);
assert.equal(readdirSync(directory, {withFileTypes: true}).filter(entry => entry.isFile() && entry.name.endsWith('.agent-project')).length, 2);
const recent = new RecentProjects(join(root, 'recent.json'));
recent.remember({path: manifest, title: 'My Project'}); recent.remember({path: manifest, title: 'My Project'});
assert.equal(recent.list().length, 1);
assert.equal(recent.list()[0].available, true);
const removedDirectory = join(root, 'Removed Project'); mkdirSync(removedDirectory);
const removedManifest = await createProjectInDirectory(removedDirectory);
recent.remember({path: removedManifest, title: 'Removed Project'});
rmSync(removedDirectory, {recursive: true});
assert.deepEqual(recent.list().map(item => [item.title, item.available]), [['Removed Project', false], ['My Project', true]]);
assert.equal(recent.remove(removedManifest), true);
assert.equal(recent.remove(manifest), true);
assert.deepEqual(recent.list(), []);
assert.equal(recent.remove(manifest), false);
console.log('Project creation, existing-file preservation, ambiguous directory refusal and recent-project history operations passed.');
